// Regenerates packages/shared/src/abis.ts from Foundry artifacts. Run `forge build` first.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '../../contracts/out')
const names = ['SkillProfileRegistry', 'ProjectEvidenceRegistry', 'SkillAttestation', 'CredentialRegistry']
let ts = '// AUTO-GENERATED by scripts/export-abis.mjs from Foundry artifacts. Do not edit.\n\n'
for (const n of names) {
  const art = JSON.parse(readFileSync(join(out, `${n}.sol`, `${n}.json`), 'utf8'))
  const key = n[0].toLowerCase() + n.slice(1)
  ts += `export const ${key}Abi = ${JSON.stringify(art.abi, null, 2)} as const\n\n`
}
ts += `export const agentIdAbi = [
  { type: 'function', name: 'balanceOf', stateMutability: 'view', inputs: [{ name: 'owner', type: 'address' }], outputs: [{ type: 'uint256' }] },
  { type: 'function', name: 'ownerOf', stateMutability: 'view', inputs: [{ name: 'tokenId', type: 'uint256' }], outputs: [{ type: 'address' }] },
  { type: 'function', name: 'tokenURI', stateMutability: 'view', inputs: [{ name: 'tokenId', type: 'uint256' }], outputs: [{ type: 'string' }] },
] as const\n`
writeFileSync(join(here, '../src/abis.ts'), ts)
console.log('wrote src/abis.ts')
